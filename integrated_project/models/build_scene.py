import sys
from pathlib import Path

import cv2
import numpy as np

HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE.parent / "part_d"))
from sim.scenario import MARKERS, OBSTACLES, ROOM  # noqa: E402

MARKER_DICT = cv2.aruco.DICT_4X4_50
MARKER_SIZE = 0.15        # m, black square side (the camera code must use the same value)
MARKER_Z = 0.11           # m, marker centre height = camera height, so it stays in frame down to the 0.35 m dock standoff
WALL_T = 0.05             # wall half-thickness
WALL_H = 0.25             # wall half-height
BORDER = 0.25             # white quiet zone on each side, as a fraction of MARKER_SIZE


def make_textures():
    tex_dir = HERE / "textures"
    tex_dir.mkdir(exist_ok=True)
    d = cv2.aruco.getPredefinedDictionary(MARKER_DICT)
    n, b = 400, int(400 * BORDER)
    for mid in MARKERS:
        img = cv2.aruco.generateImageMarker(d, mid, n)
        img = cv2.copyMakeBorder(img, b, b, b, b, cv2.BORDER_CONSTANT, value=255)
        cv2.imwrite(str(tex_dir / f"aruco_{mid}.png"), cv2.cvtColor(img, cv2.COLOR_GRAY2BGR))


def scene_xml():
    W, H = ROOM
    half = MARKER_SIZE * (1 + 2 * BORDER) / 2
    assets, markers, obstacles = [], [], []
    for mid, (mx, my, ang) in MARKERS.items():
        assets.append(f'    <texture type="2d" name="aruco_{mid}" file="textures/aruco_{mid}.png"/>\n'
                      f'    <material name="aruco_{mid}" texture="aruco_{mid}" emission="0.3"/>')
        n = np.array([np.cos(ang), np.sin(ang)])
        px, py = np.array([mx, my]) + 0.002 * n          # 2 mm off the wall surface
        markers.append(f'    <body name="marker_{mid}" pos="{px:.4f} {py:.4f} {MARKER_Z}" '
                       f'zaxis="{n[0]:.4f} {n[1]:.4f} 0">\n'
                       f'      <geom name="aruco_{mid}" type="plane" size="{half:.4f} {half:.4f} 0.01" '
                       f'material="aruco_{mid}" contype="0" conaffinity="0"/>\n    </body>')
    for i, (x0, y0, x1, y1) in enumerate(OBSTACLES, 1):
        obstacles.append(f'    <body name="obs_{i}" pos="{(x0 + x1) / 2} {(y0 + y1) / 2} 0.25">'
                         f'<geom type="box" size="{(x1 - x0) / 2} {(y1 - y0) / 2} 0.25" material="obstacle"/></body>')
    dock_id = 0
    dx, dy, dang = MARKERS[dock_id]
    pad = np.array([dx, dy]) + 0.3 * np.array([np.cos(dang), np.sin(dang)])

    ############## this is the moving obstacle
    moving_obstacle = """    <body name="obs_crossing" mocap="true" pos="0.5 2.5 0.25">
      <geom type="box" size="0.15 0.15 0.25" material="obstacle"/>
    </body>"""

    return f"""<!--
  GENERATED by models/build_scene.py from part_d/sim/scenario.py. Edit those, not this file.
  World frame: origin at the room's south-west corner, x east, y north, z up (same as Part D).
  Markers: ArUco DICT_4X4_50, black square {MARKER_SIZE} m, centres at z = {MARKER_Z} m. Dock = id {dock_id}.
-->
<mujoco model="track_a_room">
  <include file="tb3/turtlebot3_waffle_pi.xml"/>

  <option timestep="0.002"/>
  <statistic center="{W / 2} {H / 2} 0.3" extent="4"/>

  <visual>
    <headlight diffuse="0.6 0.6 0.6" ambient="0.4 0.4 0.4" specular="0 0 0"/>
    <global azimuth="90" elevation="-60" offwidth="1280" offheight="960"/>
  </visual>

  <asset>
    <texture type="skybox" builtin="gradient" rgb1="0.3 0.5 0.7" rgb2="0 0 0" width="512" height="3072"/>
    <texture type="2d" name="groundplane" builtin="checker" mark="edge" rgb1="0.55 0.55 0.5" rgb2="0.5 0.5 0.45"
             markrgb="0.7 0.7 0.7" width="300" height="300"/>
    <material name="groundplane" texture="groundplane" texuniform="true" texrepeat="4 4"/>
    <material name="wall" rgba="0.85 0.85 0.8 1"/>
    <material name="obstacle" rgba="0.5 0.72 0.55 1"/>
    <material name="dock" rgba="0.2 0.5 0.8 1"/>
{chr(10).join(assets)}
  </asset>

  <worldbody>
    <light pos="{W / 2} {H / 2} 4" dir="0 0 -1" directional="true" diffuse="0.6 0.6 0.6"/>
    <geom name="floor" type="plane" pos="{W / 2} {H / 2} 0" size="{W / 2 + 0.5} {H / 2 + 0.5} 0.05" material="groundplane"/>

    <!-- Walls: inner faces at x = 0, x = {W}, y = 0, y = {H} -->
    <geom name="wall_w" type="box" pos="{-WALL_T} {H / 2} {WALL_H}" size="{WALL_T} {H / 2 + 2 * WALL_T} {WALL_H}" material="wall"/>
    <geom name="wall_e" type="box" pos="{W + WALL_T} {H / 2} {WALL_H}" size="{WALL_T} {H / 2 + 2 * WALL_T} {WALL_H}" material="wall"/>
    <geom name="wall_s" type="box" pos="{W / 2} {-WALL_T} {WALL_H}" size="{W / 2} {WALL_T} {WALL_H}" material="wall"/>
    <geom name="wall_n" type="box" pos="{W / 2} {H + WALL_T} {WALL_H}" size="{W / 2} {WALL_T} {WALL_H}" material="wall"/>

    <!-- Obstacles (named obs_* so trials can move them, e.g. for randomised tests) -->
{chr(10).join(obstacles)}

    <!-- Moving obstacle -->
{moving_obstacle}

    <!-- Charging station pad in front of the dock marker -->
    <geom name="dock_pad" type="box" pos="{pad[0]:.3f} {pad[1]:.3f} 0.001" size="0.2 0.2 0.001" material="dock"
          contype="0" conaffinity="0"/>

    <!-- ArUco markers -->
{chr(10).join(markers)}
  </worldbody>
</mujoco>
"""


if __name__ == "__main__":
    make_textures()
    (HERE / "scene_room.xml").write_text(scene_xml())
    print("wrote", HERE / "scene_room.xml", "and", len(MARKERS), "marker textures")